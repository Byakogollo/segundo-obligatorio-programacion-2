    private void cargarTabla(){
       
        ArrayList<Area> areasOrdenadas = this.cargarAreasOrdenadasPorPorcentajeDesc();
       
        DefaultTableModel table = (DefaultTableModel) tblAreas.getModel();
                
        table.setRowCount(0);
                
                   
                
                for (Area area : areasOrdenadas) {
                        table.addRow(new Object[]{ area.getNombre() });
                    }
                
        
                     TableCellRenderer renderer = new DefaultTableCellRenderer(){
              
                        @Override
                          public Component getTableCellRendererComponent(JTable table, Object value,
                          boolean isSelected, boolean hasFocus, int row, int column) {

                              Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                                      double porcentajeAsignado = calcularPorcentajeAsignado(areasOrdenadas.get(row));

                                      if (porcentajeAsignado > 90.0) {
                                          c.setBackground(Color.RED);
                                          c.setForeground(Color.WHITE);
                                      } else if(porcentajeAsignado > 70.0 && porcentajeAsignado <=90.0){
                                          c.setBackground(Color.YELLOW);
                                          c.setForeground(Color.BLACK);
                                      }else{
                                          c.setBackground(Color.WHITE);
                                          c.setForeground(Color.BLACK);
                                      }

                                      return c;
                                  }
                              };

                           tblAreas.getColumnModel().getColumn(0).setCellRenderer(renderer);

                            
    }
    

   private ArrayList<Area> cargarAreasOrdenadasPorPorcentajeDesc() {
    ArrayList<Area> resultado = new ArrayList<>(this.modelo.getAreas());

   
    resultado.sort((a1, a2) -> Double.compare(calcularPorcentajeAsignado(a2), calcularPorcentajeAsignado(a1)));

    return resultado;
}


    private double calcularPorcentajeAsignado(Area a) {
      
        double pct = (a.salarioAnualAsignado() * 100.0) / a.getPresupuestoAnual();
     
        return pct;
    }

    private double redondear2(double v) {
        return Math.round(v * 100.0) / 100.0;
    }



