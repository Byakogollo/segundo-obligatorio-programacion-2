    private void tblAreasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblAreasMouseClicked
        DefaultTableModel table = (DefaultTableModel) tblAreas.getModel();
        
        Area seleccion = this.modelo.buscarAreaPorNombre((String)table.getValueAt(this.tblAreas.getSelectedRow(),0));
        this.lblDetalle.setText("Detalles del Area");
        this.lblArea.setText("Area Seleccionada: "+seleccion.getNombre());
        this.lblPresupuesto.setText("Presupuesto Usado: "+this.calcularPorcentajeAsignado(seleccion)+"%");
        
        this.pnlBotones.removeAll();
        this.pnlBotones.revalidate();
        this.pnlBotones.repaint();
        
        ArrayList<Empleado> listaOrdenadaPorNombre = new ArrayList<>(seleccion.getEmpleados());
        listaOrdenadaPorNombre.sort((a1,a2) -> a1.getNombre().compareTo(a2.getNombre()));
        
        for (int i =0; i<listaOrdenadaPorNombre.size();i++){
            
            
            this.generarBotones(listaOrdenadaPorNombre.get(i), i);
        }
        
       
        
    }//GEN-LAST:event_tblAreasMouseClicked

